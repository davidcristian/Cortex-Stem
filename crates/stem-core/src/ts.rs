/// One exported binding, as ts-rs sees it.
#[derive(Debug)]
struct Exported {
    /// TypeScript identifier (`AppId`).
    name: String,
    /// File relative to the export directory (`AppId.ts`).
    file: PathBuf,
    /// The declaration ts-rs writes (`type AppId = string;`).
    decl: String,
}

fn entry<T: TS + 'static>(cfg: &Config) -> Exported {
    let name = T::ident(cfg);
    let file = T::output_path().unwrap_or_else(|| panic!("{name} cannot be exported"));
    Exported {
        decl: T::decl(cfg),
        name,
        file,
    }
}

/// The single list of exported types. The drift test keeps it honest.
macro_rules! exported_types {
    ($($ty:ty),* $(,)?) => {
        fn export_everything(cfg: &Config) -> Result<(), ExportError> {
            $( <$ty as TS>::export_all(cfg)?; )*
            Ok(())
        }

        fn exported(cfg: &Config) -> Vec<Exported> {
            vec![$( entry::<$ty>(cfg) ),*]
        }
    };
}

