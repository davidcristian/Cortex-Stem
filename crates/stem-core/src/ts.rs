//! TypeScript bindings pipeline (feature `ts`, tests only).
//!
//! `cargo test -p stem-core --features ts` *is* the exporter: every type with
//! a `ts(export)` attribute gets an `export_bindings_*` test from ts-rs that
//! writes `<Name>.ts` into `TS_RS_EXPORT_DIR` (`src/lib/ipc/generated/`, set
//! in `.cargo/config.toml`; never add `export_to` paths). This module adds
//! what ts-rs does not do:
//!
//! - `index.ts`, a barrel re-exporting every binding in sorted order, so the
//!   frontend imports from one place;
//! - a drift check: [`exported_types!`] must list exactly the types that carry
//!   the attribute (scanned from this crate's sources), and the export
//!   directory must hold no stale binding files;
//! - shape checks: ids cross IPC as plain `number`/`string`, nothing exports
//!   as `bigint`, and every payload type named in `docs/ipc/` is exported.
//!
//! Running the export twice produces no change: ts-rs rewrites identical
//! files, and the barrel is only written when its content differs.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use ts_rs::{Config, ExportError, TS};

use crate::model::{
    AppFolder, AppId, AppIdentity, AppInfo, DockFacts, DockItem, DockItemKind, DockState, IconKey,
    LaunchTarget, MonitorId, MonitorInfo, RawWindow, Rect, RecycleBinState, ShellAction, ThemeInfo,
    WindowAction, WindowId, WindowInfo,
};
use crate::settings::{
    Appearance, AutoHide, AutoHideMode, Backdrop, Behavior, DockPosition, FixedItems,
    Magnification, MonitorMode, PinnedApp, Settings, SystemIntegration, ThemeMode,
};

/// One exported binding, as ts-rs sees it.
#[derive(Debug)]
struct Exported {
    /// TypeScript identifier (`AppId`).
    name: String,
    /// File relative to the export directory (`AppId.ts`).
    file: PathBuf,
    /// The declaration ts-rs writes (`type AppId = string;`).
    decl: String,
}

fn entry<T: TS + 'static>(cfg: &Config) -> Exported {
    let name = T::ident(cfg);
    let file = T::output_path().unwrap_or_else(|| panic!("{name} cannot be exported"));
    Exported {
        decl: T::decl(cfg),
        name,
        file,
    }
}

/// The single list of exported types. The drift test keeps it honest.
macro_rules! exported_types {
    ($($ty:ty),* $(,)?) => {
        fn export_everything(cfg: &Config) -> Result<(), ExportError> {
            $( <$ty as TS>::export_all(cfg)?; )*
            Ok(())
        }

        fn exported(cfg: &Config) -> Vec<Exported> {
            vec![$( entry::<$ty>(cfg) ),*]
        }
    };
}

